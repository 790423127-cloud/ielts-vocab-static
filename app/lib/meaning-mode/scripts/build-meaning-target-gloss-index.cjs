// build-meaning-target-gloss-index.cjs
// Reads words.json + meaning-6000.json, generates a browser-compatible gloss index
// for all 6000 Meaning Mode target words.
// Usage: node app/lib/meaning-mode/scripts/build-meaning-target-gloss-index.cjs

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..", "..", "..");
const WORDS_PATH = path.join(ROOT, ".static-export-cache", "words.json");
const MEANING_PATH = path.join(ROOT, "public", "data", "meaning-6000.json");
const DST = path.join(ROOT, "app", "lib", "meaning-mode", "meaning-target-gloss-index.generated.mjs");

const wordsData = JSON.parse(fs.readFileSync(WORDS_PATH, "utf-8"));
const meaningData = JSON.parse(fs.readFileSync(MEANING_PATH, "utf-8"));

const wordById = new Map(wordsData.words.map(w => [w.wordId, w]));
const entries = [];

let matched = 0;
let missing = 0;
for (const item of meaningData.items) {
  const full = wordById.get(item.wordId);
  if (!full) {
    missing++;
    continue;
  }
  if (full.word !== item.word) {
    console.error("WORD MISMATCH: " + item.wordId + " 6000=" + item.word + " full=" + full.word);
    process.exit(1);
  }

  // Extract authoritative gloss data
  const quizSenses = full.quizSenses || [];
  const quizMeaningZh = quizSenses.length > 0
    ? (quizSenses[0].quizMeaningZh || full.meaning || "")
    : (full.meaning || "");
  const meaningDetailedZh = full.meaningDetailedZh
    || (quizSenses.length > 0 ? quizSenses[0].meaningDetailedZh : null)
    || full.meaningOriginal
    || full.meaning
    || "";
  const meaningOriginal = full.meaningOriginal
    || (full.quizSenses && full.quizSenses.length > 0 ? full.quizSenses[0].quizMeaningZh : null)
    || full.meaning
    || "";

  entries.push({
    wordId: full.wordId,
    word: full.word,
    pos: full.pos || "",
    posFamily: full._posFamily || "",
    quizSenses: quizSenses.map(s => ({
      senseId: s.senseId || "",
      quizMeaningZh: s.quizMeaningZh || "",
      meaningDetailedZh: s.meaningDetailedZh || "",
      posFamily: s.posFamily || ""
    })),
    quizMeaningZh,
    meaningDetailedZh,
    meaningOriginal,
    definition: full.definition || "",
    example: full.example || "",
    exampleCn: full.exampleCn || ""
  });

  matched++;
}

if (missing > 0) {
  console.error("FATAL: " + missing + " words not found in authoritative word bank");
  process.exit(1);
}

// Verify data quality
let shortFallbackCount = 0;
for (const e of entries) {
  const from6000 = meaningData.items.find(m => m.wordId === e.wordId);
  if (from6000 && e.quizMeaningZh === from6000.meaningZh && e.quizMeaningZh.length < 6) {
    shortFallbackCount++;
  }
}

const output = [
  "// meaning-target-gloss-index.generated.mjs",
  "// Auto-generated by build-meaning-target-gloss-index.cjs. Do not edit by hand.",
  "// Generated at: " + new Date().toISOString(),
  "// Total entries: " + entries.length,
  "",
  "export const TARGET_GLOSS_INDEX = " + JSON.stringify(entries) + ";",
  "export const INDEX_VERSION = \"1.0.0\";",
  "export const INDEX_GENERATED_AT = " + JSON.stringify(new Date().toISOString()) + ";",
  ""
].join("\n");

fs.writeFileSync(DST, output, "utf-8");
console.log("Generated: " + DST);
console.log("Entries: " + entries.length + " / " + meaningData.items.length);
console.log("Missing: " + missing);
console.log("Short fallback candidates: " + shortFallbackCount);
console.log("File size: " + fs.statSync(DST).size + " bytes");
